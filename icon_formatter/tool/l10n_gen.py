"""Builds the app texts from lib/l10n/source_it.dart (Italian, the source).

Output:
- lib/l10n/strings_it.dart: class Strings, the Italian texts (the fallback);
- lib/l10n/strings_<lang>.dart: one subclass per translation in
  tool/l10n/<lang>.tsv (`key<TAB>Dart expression`); missing keys stay Italian;
- lib/l10n/strings.dart: the `S` facade used by the screens (S.key, S.fn(..)).

Run: python tool/l10n_gen.py   (then `dart format lib/l10n`)
Check: python tool/l10n_gen.py --check   (lists keys missing per language)
"""
import os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, 'lib', 'l10n', 'source_it.dart')
TSV = os.path.join(ROOT, 'tool', 'l10n')
OUT = os.path.join(ROOT, 'lib', 'l10n')

# language code -> (class suffix, name shown in the picker)
LANGS = {
    'en': ('En', 'English'),
    'es': ('Es', 'Español'),
    'fr': ('Fr', 'Français'),
    'de': ('De', 'Deutsch'),
    'pt': ('Pt', 'Português'),
}


def parse(path):
    """(key, params or None, expr) for every `static` text in the source."""
    text = open(path, encoding='utf-8').read()
    body = text[text.index('{', text.index('class S')) + 1:text.rindex('}')]
    out = []
    i = 0
    decl = re.compile(r'\s*static\s+(?:const|String)\s+(\w+)\s*(\([^)]*\))?\s*(=>|=)\s*', re.S)
    while True:
        m = decl.search(body, i)
        if not m:
            break
        start = m.end()
        # the expression runs to the `;` outside strings and brackets
        j, depth, q = start, 0, None
        while j < len(body):
            ch = body[j]
            if q:
                if ch == '\\':
                    j += 2
                    continue
                if ch == q:
                    q = None
                elif ch == '$' and body[j + 1:j + 2] == '{':
                    # interpolation: skip to its matching brace
                    k, d = j + 2, 1
                    while d:
                        if body[k] == '{':
                            d += 1
                        elif body[k] == '}':
                            d -= 1
                        k += 1
                    j = k
                    continue
            elif ch in '\'"':
                q = ch
            elif ch in '([{':
                depth += 1
            elif ch in ')]}':
                depth -= 1
            elif ch == ';' and depth == 0:
                break
            j += 1
        out.append((m.group(1), m.group(2), body[start:j].strip()))
        i = j + 1
    return out


def args_of(params):
    names = re.findall(r'(\w+)\s*(?:,|\)|$)', params.strip('()').replace('\n', ' ') + ')')
    return ', '.join(names)


def load_tsv(lang):
    p = os.path.join(TSV, f'{lang}.tsv')
    tr = {}
    if not os.path.exists(p):
        return tr
    for n, line in enumerate(open(p, encoding='utf-8').read().split('\n'), 1):
        if not line.strip() or line.startswith('#'):
            continue
        k, v = line.split('\t', 1)
        tr[k.strip()] = v.strip()
    return tr


def member(key, params, expr, override=False):
    pre = '  @override\n' if override else ''
    if params is None:
        return f'{pre}  String get {key} => {expr};\n'
    return f'{pre}  String {key}{params} => {expr};\n'


def main():
    entries = parse(SRC)
    keys = {k for k, _, _ in entries}
    head = '// GENERATED by tool/l10n_gen.py from lib/l10n/source_it.dart: do not edit.\n// ignore_for_file: type=lint\n\n'
    it = [head, '/// Italian texts: the source language and the fallback of every translation.\n',
          'class Strings {\n  const Strings();\n\n']
    for k, p, e in entries:
        it.append(member(k, p, e))
    it.append('}\n')
    open(os.path.join(OUT, 'strings_it.dart'), 'w', encoding='utf-8', newline='\n').write(''.join(it))

    check = '--check' in sys.argv
    for lang, (suffix, _) in LANGS.items():
        tr = load_tsv(lang)
        unknown = sorted(set(tr) - keys)
        missing = sorted(keys - set(tr))
        if check or unknown:
            print(f'{lang}: {len(tr)} translated, {len(missing)} missing, unknown: {unknown}')
            if check and missing:
                print('  missing:', ' '.join(missing))
        out = [head, "import 'strings_it.dart';\n\n", f'class Strings{suffix} extends Strings {{\n  const Strings{suffix}();\n\n']
        for k, p, e in entries:
            if k in tr:
                out.append(member(k, p, tr[k], override=True))
        out.append('}\n')
        open(os.path.join(OUT, f'strings_{lang}.dart'), 'w', encoding='utf-8', newline='\n').write(''.join(out))

    s = [head]
    s.append("import 'strings_it.dart';\n")
    for lang in LANGS:
        s.append(f"import 'strings_{lang}.dart';\n")
    s.append('\n/// App languages: code -> name shown in Impostazioni › Aspetto.\n')
    s.append("const appLanguages = <String, String>{\n  'it': 'Italiano',\n")
    for lang, (_, name) in LANGS.items():
        s.append(f"  '{lang}': '{name}',\n")
    s.append('};\n\n')
    s.append('Strings stringsFor(String code) => switch (code) {\n')
    for lang, (suffix, _) in LANGS.items():
        s.append(f"      '{lang}' => const Strings{suffix}(),\n")
    s.append('      _ => const Strings(),\n    };\n\n')
    s.append('/// Texts of the current language (set by AppState from the setting or the system).\n')
    s.append('class S {\n  S._();\n\n  static Strings current = const Strings();\n\n')
    for k, p, e in entries:
        if p is None:
            s.append(f'  static String get {k} => current.{k};\n')
        else:
            s.append(f'  static String {k}{p} => current.{k}({args_of(p)});\n')
    s.append('}\n')
    open(os.path.join(OUT, 'strings.dart'), 'w', encoding='utf-8', newline='\n').write(''.join(s))
    # test: every text of every language is non-empty and fully interpolated
    t = [head, "import 'package:flutter_test/flutter_test.dart';\nimport 'package:icon_formatter/l10n/strings.dart';\n\n"]
    t.append('void main() {\n  for (final code in appLanguages.keys) {\n    test(\'texts of $code\', () {\n      S.current = stringsFor(code);\n      final all = <String>[\n')
    for k, p, e in entries:
        if p is None:
            t.append(f'        S.{k},\n')
        else:
            args = []
            for typ, name in re.findall(r'(\w+\??)\s+(\w+)', p):
                args.append('1' if typ.startswith('int') else "'x'")
            t.append(f'        S.{k}({", ".join(args)}),\n')
    t.append("      ];\n      for (final s in all) {\n        expect(s.trim(), isNotEmpty);\n        expect(s.contains(RegExp(r'\\$[a-z{]')), isFalse, reason: s);\n      }\n    });\n  }\n}\n")
    open(os.path.join(ROOT, 'test', 'l10n_test.dart'), 'w', encoding='utf-8', newline='\n').write(''.join(t))
    print(f'{len(entries)} texts, languages: it + {", ".join(LANGS)}')


if __name__ == '__main__':
    main()
